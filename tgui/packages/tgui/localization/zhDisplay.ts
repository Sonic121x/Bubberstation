export function chineseDisplay(value: string): string {
  return Object.hasOwn(displayNames, value)
    ? displayNames[value]
    : value;
}

type DropdownOptions = ComponentProps<typeof Dropdown>['options'];

export function chineseDropdownOptions(options: DropdownOptions): DropdownOptions {
  return options?.map((option) =>
    typeof option === 'object'
      ? {
          ...option,
          displayText: typeof option.displayText === 'string'
            ? chineseDisplay(option.displayText)
            : option.displayText,
        }
      : { displayText: chineseDisplay(String(option)), value: option },
  );
}
