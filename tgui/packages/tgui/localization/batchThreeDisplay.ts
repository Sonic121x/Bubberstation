export function batchThreeDisplay(value: string): string {
  return Object.hasOwn(labels, value) ? labels[value] : chineseDisplay(value);
}

export function chromosomeDisplay(value: string): string {
  return value === 'Power' ? '强化染色体' : batchThreeDisplay(value);
}

export function materialDisplay(value: string): string {
  const key = value.toLowerCase();
  return Object.hasOwn(materials, key) ? materials[key] : value;
}

export function areaDisplay(value: string, data: BatchDisplayData): string {
  return ownDisplay(data.areaDisplay, value) ?? batchThreeDisplay(value);
}

export function recordDisplay(value: string, data: BatchDisplayData): string {
  if (typeof value !== 'string') return value;
  return ownDisplay(data.recordDisplay, value) ?? ownDisplay(data.jobDisplay, value)
    ?? ownDisplay(data.speciesDisplay, value.toLowerCase()) ?? batchThreeDisplay(value);
}

function ownDisplay(mapping: Record<string, string> | undefined, value: string): string | undefined {
  return mapping && Object.hasOwn(mapping, value) ? mapping[value] : undefined;
}
