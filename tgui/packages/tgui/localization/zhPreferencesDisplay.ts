const parts = Object.keys(names).sort((a, b) => b.length - a.length);

export function chineseDisplay(value: string): string {
  const common = commonDisplay(value);
  if (common !== value) return common;
  const lower = value.toLowerCase();
  if (Object.hasOwn(names, lower)) return names[lower];
  let remaining = lower;
  let result = '';
  while (remaining) {
    const separator = remaining.match(/^[\s(),+&.\-\d]+/);
    if (separator) {
      result += separator[0];
      remaining = remaining.slice(separator[0].length);
      continue;
    }
    const part = parts.find(
      (key) => remaining.startsWith(key) &&
        (!remaining[key.length] || /[\s(),+&.\-\d]/.test(remaining[key.length])),
    );
    if (!part) return value;
    result += names[part];
    remaining = remaining.slice(part.length);
  }
  return result;
}

