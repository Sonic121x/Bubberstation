export function display(raw: string): string {
  return Object.hasOwn(labels, raw) ? labels[raw] : raw;
}

export function options(raw: string[]) {
  return raw.map((value) => ({ displayText: display(value), value }));
}

interface Setting {
  type?: string;
  value: string | number | boolean;
  true_text?: string;
  false_text?: string;
}

export function value(setting: Setting) {
  if (setting.type === 'type' && typeof setting.value === 'string') {
    return display(setting.value);
  }
  if (setting.type === 'boolean') {
    return display((setting.value ? setting.true_text : setting.false_text) ?? '');
  }
  return setting.value;
}
